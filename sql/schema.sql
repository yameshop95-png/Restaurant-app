create or replace function public.assign_order_number()
returns trigger language plpgsql security definer set search_path to '' as $$
begin
  if new.number is null then
    perform pg_advisory_xact_lock(hashtext('restaurant-app.order-number'));
    -- Đơn đầu tiên của khách thật là 79; từ đó trở đi tiếp tục theo đơn lớn nhất
    select greatest(coalesce(max(number), 0), 78) + 1 into new.number from public.orders;
  end if;
  new.data := jsonb_set(new.data, '{number}', to_jsonb(new.number));
  return new;
end $$;

