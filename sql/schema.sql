create or replace function public.match_zone(address text, zones jsonb)
returns jsonb language plpgsql immutable set search_path to '' as $$
declare
  t text := ' ' || btrim(regexp_replace(lower(coalesce(address, '')), '[^a-z0-9]+', ' ', 'g')) || ' ';
  z jsonb;
  p text;
  k text;
  rest text;
  pos int;
  hit boolean;
  score numeric;
  best jsonb;
  best_score numeric := -1;
begin
  if btrim(t) = '' then return null; end if;
  for z in select value from jsonb_array_elements(coalesce(zones, '[]'::jsonb)) loop
    for p in select value from jsonb_array_elements_text(coalesce(z -> 'places', '[]'::jsonb)) loop
      k := btrim(regexp_replace(lower(p), '[^a-z0-9]+', ' ', 'g'));
      continue when k = '';
      hit := false;
      rest := t;
      loop
        pos := strpos(rest, ' ' || k || ' ');
        exit when pos = 0;
        if substr(rest, pos + length(k) + 2) !~ '^(st|street|rd|road|pl|place|ave|avenue|dr|drive|cres|crescent|ct|court|way|ln|lane|hwy|highway|pde|parade|cct|circuit|cl|close|tce|terrace|blvd|gr|grove)\M' then
          hit := true;
          exit;
        end if;
        rest := substr(rest, pos + 1);
      end loop;
      continue when not hit;
      score := case when k ~ '^\d+$' then length(k) / 100.0 else length(k) end;
      if score > best_score then
        best := z;
        best_score := score;
      end if;
    end loop;
  end loop;
  return best;
end $$;

create or replace function public.public_shop()
returns jsonb language sql stable security definer set search_path to '' as $$
  select jsonb_build_object(
    'shop', (
      select jsonb_build_object(
        'shopName', coalesce(s.data ->> 'shopName', ''),
        'shopPhone', coalesce(s.data ->> 'shopPhone', ''),
        'shopAddress', coalesce(s.data ->> 'shopAddress', ''),
        'logo', s.data -> 'logo',
        'shippingZones', coalesce(s.data -> 'shippingZones', public.default_zones()),
        'webOrdering', coalesce(s.data -> 'webOrdering', '{}'::jsonb)
      ) from public.shop_settings s where s.id = 1
    ),
    'menu', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', m.id,
        'name', m.data ->> 'name',
        'price', (m.data ->> 'price')::numeric,
        'portion', left(coalesce(m.data ->> 'portion', ''), 80),
        'available', coalesce((m.data ->> 'available')::boolean, true)
      ) order by m.position, m.id)
      from public.menu_items m
    ), '[]'::jsonb),
    'now', to_jsonb(now())
  )
$$;

