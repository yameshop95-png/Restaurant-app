create or replace function public.my_role()
returns text language sql stable security definer set search_path to '' as $$
  select a.role from public.device_sessions s
  join public.staff_accounts a on a.id = s.account_id and a.version = s.account_version and not a.removed
  where s.user_id = auth.uid()
$$;

create or replace function public.is_member()
returns boolean language sql stable security definer set search_path to '' as $$
  select coalesce(public.my_role() in ('owner', 'staff'), false)
$$;

create or replace function public.my_account()
returns jsonb language sql stable security definer set search_path to '' as $$
  select jsonb_build_object('id', a.id, 'name', a.name, 'role', a.role)
  from public.device_sessions s
  join public.staff_accounts a on a.id = s.account_id and a.version = s.account_version and not a.removed
  where s.user_id = auth.uid()
$$;

create or replace function public.pin_login(pin text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare
  uid uuid := auth.uid();
  sess public.device_sessions;
  acc public.staff_accounts;
  attempts int;
begin
  if uid is null then return jsonb_build_object('error', 'no_session'); end if;
  insert into public.device_sessions (user_id) values (uid) on conflict do nothing;
  select * into sess from public.device_sessions where user_id = uid for update;
  if sess.locked_until > now() then
    return jsonb_build_object('error', 'locked', 'until', sess.locked_until);
  end if;
  if (select count(*) from public.pin_failures where at > now() - interval '10 minutes') >= 30 then
    return jsonb_build_object('error', 'busy');
  end if;

  if pin ~ '^\d{4}$' then
    select * into acc from public.staff_accounts
      where not removed and pin_hash = extensions.crypt(pin, pin_hash) limit 1;
  end if;

  if acc.id is null then
    insert into public.pin_failures default values;
    attempts := sess.failed_attempts + 1;
    update public.device_sessions
      set failed_attempts = case when attempts >= 5 then 0 else attempts end,
          locked_until = case when attempts >= 5 then now() + interval '5 minutes' end
      where user_id = uid;
    if attempts >= 5 then
      return jsonb_build_object('error', 'locked', 'until', now() + interval '5 minutes');
    end if;
    return jsonb_build_object('error', 'wrong', 'left', 5 - attempts);
  end if;

  update public.device_sessions
    set account_id = acc.id, account_version = acc.version, failed_attempts = 0, locked_until = null, signed_in_at = now()
    where user_id = uid;
  return jsonb_build_object('id', acc.id, 'name', acc.name, 'role', acc.role);
end $$;

create or replace function public.pin_logout()
returns void language sql security definer set search_path to '' as $$
  update public.device_sessions set account_id = null, account_version = null where user_id = auth.uid()
$$;

create or replace function public.list_staff()
returns table(id uuid, name text, role text, created_at timestamptz)
language plpgsql stable security definer set search_path to '' as $$
begin
  if public.my_role() is distinct from 'owner' then raise exception 'Chỉ chủ quán mới xem được'; end if;
  return query select a.id, a.name, a.role, a.created_at from public.staff_accounts a
    where not a.removed order by a.role, a.created_at;
end $$;

create or replace function public.save_staff(staff_id uuid, staff_name text, staff_role text, new_pin text)
returns uuid language plpgsql security definer set search_path to '' as $$
declare
  me uuid := (select s.account_id from public.device_sessions s where s.user_id = auth.uid());
  prev public.staff_accounts;
  saved uuid;
begin
  if public.my_role() is distinct from 'owner' then raise exception 'Chỉ chủ quán mới sửa được'; end if;
  if coalesce(trim(staff_name), '') = '' then raise exception 'Cần nhập tên'; end if;
  if staff_role not in ('owner', 'staff') then raise exception 'Quyền không hợp lệ'; end if;
  if new_pin is not null and new_pin !~ '^\d{4}$' then raise exception 'Mã PIN phải gồm đúng 4 chữ số'; end if;
  if new_pin is not null and exists (
    select 1 from public.staff_accounts a
    where not a.removed and a.pin_hash = extensions.crypt(new_pin, a.pin_hash) and a.id is distinct from staff_id
  ) then
    raise exception 'Mã PIN này đã có người dùng, chọn mã khác';
  end if;

  if staff_id is null then
    if new_pin is null then raise exception 'Cần nhập mã PIN'; end if;
    insert into public.staff_accounts (name, role, pin_hash)
      values (trim(staff_name), staff_role, extensions.crypt(new_pin, extensions.gen_salt('bf')))
      returning id into saved;
    return saved;
  end if;

  select * into prev from public.staff_accounts where id = staff_id and not removed for update;
  if prev.id is null then raise exception 'Không tìm thấy tài khoản'; end if;
  if prev.role = 'owner' and staff_role <> 'owner'
     and not exists (select 1 from public.staff_accounts where role = 'owner' and not removed and id <> staff_id) then
    raise exception 'Phải còn ít nhất một chủ quán';
  end if;
  update public.staff_accounts set
    name = trim(staff_name),
    role = staff_role,
    pin_hash = case when new_pin is null then pin_hash else extensions.crypt(new_pin, extensions.gen_salt('bf')) end,
    version = case when new_pin is not null or staff_role <> prev.role then version + 1 else version end
  where id = staff_id;
  -- Chủ quán tự đổi PIN của mình: máy đang dùng vẫn giữ đăng nhập
  if staff_id = me then
    update public.device_sessions set account_version = (select version from public.staff_accounts where id = me)
      where user_id = auth.uid();
  end if;
  return staff_id;
end $$;

create or replace function public.remove_staff(staff_id uuid)
returns void language plpgsql security definer set search_path to '' as $$
begin
  if public.my_role() is distinct from 'owner' then raise exception 'Chỉ chủ quán mới xoá được'; end if;
  if (select role from public.staff_accounts where id = staff_id) = 'owner'
     and not exists (select 1 from public.staff_accounts where role = 'owner' and not removed and id <> staff_id) then
    raise exception 'Phải còn ít nhất một chủ quán';
  end if;
  update public.staff_accounts set removed = true, version = version + 1 where id = staff_id;
end $$;

